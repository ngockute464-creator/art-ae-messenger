import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const app=readFileSync('public/app.js','utf8');
const css=readFileSync('public/styles.css','utf8');
const js=readFileSync('server/projects-drawer.js','utf8');
assert.match(app,/class="projectsDrawerToggle" data-act="projectsDrawerToggle"/);
assert.match(app,/aria-controls="artaeProjectsDrawer"/);
assert.match(app,/class="sidebar" id="artaeProjectsDrawer"/);
assert.match(app,/class="projectsDrawerScrim" data-act="projectsDrawerClose"/);
assert.match(app,/projectsDrawerOpen\?' projects-drawer-open'/);
assert.match(css,/@media\(min-width:651px\)/);
assert.match(css,/\.app \.workspace\{grid-template-columns:minmax\(0,1fr\)!important/);
assert.match(css,/\.app\.projects-drawer-open \.workspace>\.sidebar/);
assert.match(css,/\.app\.projects-drawer-open \.projectsDrawerScrim/);
assert.match(css,/@media\(max-width:650px\)\{\s*\.projectsDrawerToggle,\.projectsDrawerScrim\{display:none!important\}/);
let opened=false,expanded='false',focused=0;
const button={setAttribute:(k,v)=>{if(k==='aria-expanded')expanded=v},focus(){focused++}};
const appElement={classList:{toggle(_name,val){opened=val}},querySelector:s=>s==='.projectsDrawerToggle'?button:null};
const listeners={};
const root={querySelector:s=>s==='.app'?appElement:s==='.projectsDrawerToggle'?button:null,
 addEventListener:(type,fn)=>listeners[type]=fn};
const context={root,window:{matchMedia:()=>({matches:false})},queueMicrotask,document:{},console};
const control=runInNewContext(js+'\n({toggleProjectsDrawer,closeProjectsDrawer})',context);
control.toggleProjectsDrawer();
assert.equal(opened,true);
assert.equal(expanded,'true');
let prevented=false;
listeners.keydown({key:'Escape',preventDefault(){prevented=true}});
assert.equal(prevented,true);
assert.equal(opened,false);
assert.equal(expanded,'false');
assert.equal(focused,1,'Keyboard focus returns to toggle');
control.toggleProjectsDrawer();
control.closeProjectsDrawer();
assert.equal(opened,false);
console.log('PROJECT_DRAWER_OK wide_screen=true compact_default=true backdrop=true escape=true mobile_preserved=true');

import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const html=readFileSync('public/index.html','utf8');
const app=readFileSync('public/app.js','utf8');
const css=readFileSync('public/styles.css','utf8');
const sw=readFileSync('public/sw.js','utf8');
const favicon=readFileSync('public/favicon.png');
const brand=readFileSync('public/ae-brand.svg','utf8');
const icon=readFileSync('public/icon.svg','utf8');
const manifest=JSON.parse(readFileSync('public/manifest.webmanifest','utf8'));
assert.equal(createHash('sha256').update(favicon).digest('hex'),'0ad9d4d5a510ab8ee27e5d8c5f4e2cc9ebdfb6f833cc586e4239d3edda4f1401','Exact uploaded fav_AE_Logo.png');
assert.match(html,/rel="icon"[^>]+href="\/favicon\.png"/);
assert.match(app,/<img class="artaeBrandLogo" src="\/ae-brand\.svg"/);
assert.doesNotMatch(app,/>◉ АРТ-АЕ<\/button>/);
assert.match(css,/\.artaeBrandLogo\{/);
assert.equal(brand,icon,'PWA and header use the same supplied-logo artwork');
assert.ok(brand.startsWith('<svg'));
assert.ok(manifest.icons.some(x=>x.src==='icon.svg'));
for(const path of ['favicon.png','ae-brand.svg','icon.svg'])assert.ok(sw.includes("'./"+path+"'"),'Offline PWA asset '+path);
console.log('ARTAE_BRANDING_OK supplied_favicon_exact=true header=true pwa=true cached=true');
